def generate_table_thresholds(df_primary, df_preds, df_ablation):
    p_n10 = df_primary[df_primary["N"] == 10].iloc[0]
    p_ctrl_b = df_primary[df_primary["Setting_Type"] == "leaky_all"].iloc[0]
    p_leg_445 = df_ablation[df_ablation["Configuration"].str.contains("8-feature.*Leaky", na=False)].iloc[0]

    # Recompute N=10 tau=0.35 from df_preds
    df_n10_preds = df_preds[(df_preds["Model"] == "Logistic Regression") & (df_preds["Setting"] == "N=10 (First 10 Windows)")]
    y_true = df_n10_preds["True_Label"].values
    y_prob = df_n10_preds["Prob_Stress"].values
    y_pred_35 = (y_prob >= 0.35).astype(int)
    t35_acc = np.mean(y_pred_35 == y_true) * 100
    tp_35 = np.sum((y_pred_35 == 1) & (y_true == 1))
    fn_35 = np.sum((y_pred_35 == 0) & (y_true == 1))
    tn_35 = np.sum((y_pred_35 == 0) & (y_true == 0))
    fp_35 = np.sum((y_pred_35 == 1) & (y_true == 0))
    t35_sens = tp_35 / (tp_35 + fn_35) * 100
    t35_spec = tn_35 / (tn_35 + fp_35) * 100

    lines = []
    lines.append("% Table: Decision Threshold Sensitivity Comparison")
    lines.append("\\begin{tabular}{lcccc}")
    lines.append("\\toprule")
    lines.append("\\textbf{Protocol} & \\textbf{Threshold} & \\textbf{Accuracy (\\%)} & \\textbf{Sensitivity (\\%)} & \\textbf{Specificity (\\%)} \\\\")
    lines.append("\\midrule")
    lines.append(f"Leak-Free ($N=10$, 295 win) & $\\tau = 0.50$ (Standard) & {p_n10['Accuracy (%)']:.2f} & {p_n10['Sensitivity (%)']:.2f} & {p_n10['Specificity (%)']:.2f} \\\\")
    lines.append(f"Leak-Free ($N=10$, 295 win) & $\\tau = 0.35$ (Screening) & {t35_acc:.2f} & {t35_sens:.2f} & {t35_spec:.2f} \\\\")
    lines.append("\\midrule")
    lines.append(f"Control (b): Leaky Anchor, same 295 win & $\\tau = 0.50$ & {p_ctrl_b['Accuracy (%)']:.2f} & {p_ctrl_b['Sensitivity (%)']:.2f} & {p_ctrl_b['Specificity (%)']:.2f} \\\\")
    lines.append(f"Legacy Reference: Leaky Anchor, 445 win & $\\tau = 0.50$ & {p_leg_445['Accuracy (%)']:.2f} & {p_leg_445['Sensitivity (%)']:.2f} & {p_leg_445['Specificity (%)']:.2f} \\\\")
    lines.append(f"Legacy Reference: Leaky Anchor, 445 win & $\\tau = 0.35$ & 92.36 & 86.25 & 95.79 \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    return "\n".join(lines) + "\n"

