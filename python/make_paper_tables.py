def load_data():
    df_primary = pd.read_csv(os.path.join(CAL_DIR, "calibration_length_primary_model.csv"))
    df_all = pd.read_csv(os.path.join(CAL_DIR, "calibration_length_all_models.csv"))
    df_contrasts = pd.read_csv(os.path.join(CAL_DIR, "paired_contrasts_bootstrap.csv"))
    df_ablation = pd.read_csv(os.path.join(CAL_DIR, "leak_free_ablation_results.csv"))
    df_preds = pd.read_csv(os.path.join(CAL_DIR, "calibration_length_window_predictions.csv"))

    with open(RAW_BIQUAD_JSON, "r") as f:
        biquad_data = json.load(f)

    # Parse HIL report
    hil_metrics = {}
    with open(HIL_REPORT_TXT, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            if "Wire Shannon Entropy:" in line:
                hil_metrics["entropy"] = float(line.split(":")[1].split()[0])
            elif "Chi-Square Uniformity:" in line:
                # chi^2=257.79, p=0.4394 [PASS]
                parts = line.split(":")[1].split(",")
                hil_metrics["chi2"] = float(parts[0].replace("chi^2=", "").strip())
                hil_metrics["p_val"] = float(parts[1].split()[0].replace("p=", "").strip())
            elif "Evaluated Packets:" in line:
                hil_metrics["packets"] = int(line.split(":")[1].split()[0].replace(",", ""))

    return df_primary, df_all, df_contrasts, df_ablation, df_preds, biquad_data, hil_metrics

